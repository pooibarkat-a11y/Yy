    suspend fun askAssistant(userQuery: String, chatHistory: List<ChatMessage> = emptyList()): String = withContext(Dispatchers.IO) {
        val apiKey = try {
            BuildConfig.GEMINI_API_KEY
        } catch (_: Throwable) {
            ""
        }

        if (apiKey.isBlank() || apiKey == "MY_GEMINI_API_KEY") {
            return@withContext provideLocalFallbackAnswer(userQuery)
        }

        val modelsToTry = listOf(
            "gemini-3.5-flash",
            "gemini-2.5-flash",
            "gemini-flash-latest"
        )

        for (modelName in modelsToTry) {
            try {
                val url = "https://generativelanguage.googleapis.com/v1beta/models/$modelName:generateContent?key=$apiKey"

                val rootJson = JSONObject()

                // System Instruction
                val sysInstructionObj = JSONObject()
                val sysParts = JSONArray()
                sysParts.put(JSONObject().put("text", SYSTEM_INSTRUCTION))
                sysInstructionObj.put("parts", sysParts)
                rootJson.put("systemInstruction", sysInstructionObj)

                // Generation Config for superior depth and creativity
                val genConfig = JSONObject()
                genConfig.put("temperature", 0.7)
                genConfig.put("topP", 0.95)
                genConfig.put("maxOutputTokens", 2048)
                rootJson.put("generationConfig", genConfig)

                // Contents array
                val contentsArray = JSONArray()

                // Include last 6 turns of history for great contextual continuity
                val recentHistory = chatHistory.takeLast(6)
                for (msg in recentHistory) {
                    val role = if (msg.sender == MessageSender.USER) "user" else "model"
                    val contentObj = JSONObject()
                    contentObj.put("role", role)
                    val parts = JSONArray()
                    parts.put(JSONObject().put("text", msg.text))
                    contentObj.put("parts", parts)
                    contentsArray.put(contentObj)
                }

                // Current user query
                val currentTurn = JSONObject()
                currentTurn.put("role", "user")
                val currentParts = JSONArray()
                currentParts.put(JSONObject().put("text", userQuery))
                currentTurn.put("parts", currentParts)
                contentsArray.put(currentTurn)

                rootJson.put("contents", contentsArray)

                val body = rootJson.toString().toRequestBody("application/json".toMediaType())
                val request = Request.Builder()
                    .url(url)
                    .post(body)
                    .build()

                val response = client.newCall(request).execute()
                if (response.isSuccessful) {
                    val responseBody = response.body?.string() ?: ""
                    val jsonResponse = JSONObject(responseBody)
                    val candidates = jsonResponse.optJSONArray("candidates")
                    val firstCandidate = candidates?.optJSONObject(0)
                    val content = firstCandidate?.optJSONObject("content")
                    val parts = content?.optJSONArray("parts")
                    val replyText = parts?.optJSONObject(0)?.optString("text")

                    if (!replyText.isNullOrBlank()) {
                        return@withContext replyText
                    }
                }
            } catch (_: Exception) {
                // Try next model candidate
            }
        }

        provideLocalFallbackAnswer(userQuery)
    }

