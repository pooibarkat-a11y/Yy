package com.example.data

// =================================================================================================
// DATA MODELS FOR ISLAMIC ACADEMY & LEARNING HUB
// =================================================================================================

data class ProphetStory(
    val id: String,
    val name: String,
    val title: String,
    val summary: String,
    val keyLessons: List<String>,
    val quranAyah: String,
    val quranSurahRef: String,
    val fullStory: String,
    val miracles: List<String> = emptyList(),
    val peopleSentTo: String = "",
    val chronologicalOrder: Int = 0
)

data class SeerahChapter(
    val id: String,
    val title: String,
    val period: String,
    val description: String,
    val keyEvents: List<String>,
    val propheticWisdom: String
)

data class PillarOfIslam(
    val number: Int,
    val name: String,
    val titleArabic: String,
    val meaning: String,
    val evidence: String,
    val conditionsAndDetails: List<String>,
    val virtues: String
)

data class PillarOfIman(
    val number: Int,
    val name: String,
    val titleArabic: String,
    val definition: String,
    val dalil: String,
    val detailedPoints: List<String>,
    val fruitsOfFaith: String
)

data class FiqhLessonStep(
    val stepNumber: Int,
    val title: String,
    val description: String,
    val duaOrDhikr: String? = null,
    val ruling: String = "فرض" // فرض أو سنة
)

data class FiqhTopic(
    val id: String,
    val title: String,
    val category: String, // "وضوء", "صلاة", "تيمم", "صيام", "زكاة", "آداب المسجد", "أخلاق"
    val summary: String,
    val steps: List<FiqhLessonStep> = emptyList(),
    val pillars: List<String> = emptyList(),
    val sunan: List<String> = emptyList(),
    val invalidators: List<String> = emptyList(),
    val tips: List<String> = emptyList()
)

data class IslamicQA(
    val id: String,
    val category: String, // "عقيدة", "فقه", "سيرة", "قرآن وأخلاق"
    val question: String,
    val answer: String,
    val evidence: String
)

data class QuizQuestion(
    val id: String,
    val category: String,
    val question: String,
    val options: List<String>,
    val correctIndex: Int,
    val explanation: String
)

data class EducationalFlashcard(
    val id: String,
    val category: String,
    val frontTitle: String,
    val frontHint: String,
    val backContent: String,
    val dalil: String
)

data class KidsLesson(
    val id: String,
    val title: String,
    val iconEmoji: String,
    val category: String, // "قصة", "أدب", "عقيدة الصغار", "أذكار"
    val simpleText: String,
    val morals: List<String>,
    val funQuizQuestion: String,
    val funQuizAnswer: String
)

